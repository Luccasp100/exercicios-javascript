// Teste 1
let x = 3;
let y = 2;
let z = (x * y) + 5;
let resposta;
if (z <= 0) {
  resposta = 'A';
} else if (z <= 100) {
  resposta = 'B';
} else {
  resposta = 'C';
}
alert(`x: ${x}, y: ${y}, z: ${z}, Resposta: ${resposta}`);

